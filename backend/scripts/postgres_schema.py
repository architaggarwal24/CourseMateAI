"""Write migrations/postgres/NNNN_baseline.sql: the PostgreSQL schema equal to the SQLite one after every migration
(Phase 3 Stage 4e; docs/postgres.md).

    python scripts/postgres_schema.py            (from backend/; rewrites the baseline for the newest version)

It builds a fresh SQLite database from migrations/, reads its schema and translates it: INTEGER -> BIGINT, an
`id INTEGER PRIMARY KEY` -> an identity column, REAL -> DOUBLE PRECISION, TIMESTAMP / DATE -> TEXT (the app stores
ISO strings), CURRENT_TIMESTAMP defaults -> the same text format, tables in foreign-key order, and SQLite's
triggers -> PL/pgSQL. Later schema changes are ordinary numbered files next to it (tests check that every SQLite
migration after the baseline has its PostgreSQL twin).
"""
import re
import sqlite3
import sys
import tempfile
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from database.migrate import MIGRATIONS_DIR, discover, migrate  # noqa: E402

PG_DIR = MIGRATIONS_DIR / "postgres"
NOW_TEXT = "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))"

TRIGGERS = """
-- reward_events is append-only (SQLite: the triggers of 0004). Deleting a user may still remove theirs.
CREATE FUNCTION reward_events_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'reward_events is append-only';
    END IF;
    IF EXISTS (SELECT 1 FROM users WHERE id = OLD.user_id) THEN
        RAISE EXCEPTION 'reward_events is append-only';
    END IF;
    RETURN OLD;
END $$;
CREATE TRIGGER reward_events_no_update BEFORE UPDATE ON reward_events
    FOR EACH ROW EXECUTE FUNCTION reward_events_append_only();
CREATE TRIGGER reward_events_no_delete BEFORE DELETE ON reward_events
    FOR EACH ROW EXECUTE FUNCTION reward_events_append_only();
"""


def _column_types(sql: str) -> str:
    s = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
    s = re.sub(r"^(\s*id\s+)INTEGER\s+PRIMARY\s+KEY\b", r"\1BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I | re.M)
    s = re.sub(r"\bTIMESTAMP\s+DEFAULT\s+CURRENT_TIMESTAMP\b", f"TEXT DEFAULT {NOW_TEXT}", s, flags=re.I)
    s = re.sub(r"\b(TIMESTAMP|DATETIME|DATE)\b", "TEXT", s, flags=re.I)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s, flags=re.I)
    s = re.sub(r"\bBOOLEAN\b", "BIGINT", s, flags=re.I)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)
    s = re.sub(r"\bBLOB\b", "BYTEA", s, flags=re.I)
    s = re.sub(r"\s+COLLATE\s+NOCASE\b", "", s, flags=re.I)
    return s


def _order(tables: dict) -> list:
    """Tables so that every REFERENCES target comes first."""
    deps = {name: set(re.findall(r"REFERENCES\s+([a-z_]+)", sql, re.I)) - {name} for name, sql in tables.items()}
    out, seen = [], set()

    def visit(n):
        if n in seen or n not in tables:
            return
        seen.add(n)
        for d in sorted(deps[n]):
            visit(d)
        out.append(n)
    for n in sorted(tables):
        visit(n)
    return out


def baseline_sql() -> tuple:
    version = discover()[-1].version
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "schema.db"
        migrate(path)
        c = sqlite3.connect(path)
        rows = c.execute("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL "
                         "AND name NOT LIKE 'sqlite_%' AND tbl_name != 'schema_migrations'").fetchall()
        c.close()
    tables = {name: sql for kind, name, _, sql in rows if kind == "table"}
    indexes = [sql for kind, _, _, sql in rows if kind == "index"]
    parts = [f"-- {version:04d}: the PostgreSQL baseline - the schema of SQLite migrations 0001-{version:04d}.",
             "-- Generated by scripts/postgres_schema.py; do not edit (add a new numbered migration instead).", ""]
    for name in _order(tables):
        parts.append(_column_types(tables[name]).rstrip().rstrip(";") + ";\n")
    parts += [_column_types(sql).rstrip().rstrip(";") + ";" for sql in indexes]
    parts.append(TRIGGERS)
    return version, "\n".join(parts)


def main() -> int:
    version, sql = baseline_sql()
    PG_DIR.mkdir(exist_ok=True)
    for old in PG_DIR.glob("*_baseline.sql"):
        old.unlink()
    target = PG_DIR / f"{version:04d}_baseline.sql"
    target.write_text(sql, encoding="utf-8")
    print(f"wrote {target.relative_to(BACKEND)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
